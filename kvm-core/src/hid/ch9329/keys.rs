//! Keyboard maps (USB HID usage) aligned with `ch9329.js`.

pub const KEYBOARD_RELEASE: [u8; 14] = [
    0x57, 0xAB, 0x00, 0x02, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C,
];

pub fn is_modifier(code: &str) -> bool {
    control_key_bit(code).is_some()
}

pub fn control_key_bit(code: &str) -> Option<u8> {
    Some(match code {
        "ShiftLeft" => 0x02,
        "ShiftRight" => 0x20,
        "ControlLeft" => 0x01,
        "ControlRight" => 0x10,
        "AltLeft" => 0x04,
        "AltRight" => 0x40,
        "MetaLeft" => 0x08,
        "MetaRight" => 0x80,
        _ => return None,
    })
}

